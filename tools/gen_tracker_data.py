"""Generate the map tracker's Lua data tables from the files in data/.

    python tools/gen_tracker_data.py                              # from data/
    python tools/gen_tracker_data.py --source ../afterimage_rando # refresh data/ from the randomizer repo first

Writes into AfterimageMapTracker/Scripts/:
  data_positions.lua  check key -> world { x, z } (data/positions.tsv, data/rocks.tsv)
  data_locations.lua  check key -> save id, kind, area, room, vanilla item (English) and its icon frame
  data_icons.lua      English item name -> icon frame, for items the randomizer's list names

Inputs (data/, copied from the randomizer repo with --source; this is the
tracker part of that repo's tools/gen_lua_data.py):
  locations.json      apworld/afterimage/data/locations.json (every location: key, kind, save id, item)
  items.json          apworld/afterimage/data/items.json (the randomizer's item pool, for data_icons.lua)
  positions.tsv       world positions of the checks (CHECK rows)
  rocks.tsv           coin rocks: sublevel, actor, class, save id, x, z, ...
  item_names_en.tsv   item id -> English name
  item_icons.tsv      item id -> icon frame (tools/item_icons.py)
"""
from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
SCRIPTS = ROOT / "AfterimageMapTracker" / "Scripts"
HEADER = "-- Generated by tools/gen_tracker_data.py. Do not edit."
# data/<name> <- <randomizer repo>/<path>
SOURCES = {
    "locations.json": "apworld/afterimage/data/locations.json",
    "items.json": "apworld/afterimage/data/items.json",
    "positions.tsv": "data/positions.tsv",
    "rocks.tsv": "data/rocks.tsv",
    "item_names_en.tsv": "data/item_names_en.tsv",
    "item_icons.tsv": "data/item_icons.tsv",
}
COIN_FRAME = "/Game/Assets/UMG/TextureAtlases/HUD/Frames/ST_HUD1_Button_Gold.ST_HUD1_Button_Gold"   # the HUD's dew icon


def write(name: str, lines: list[str]) -> None:
    (SCRIPTS / name).write_text("\n".join([HEADER, "return {", *lines, "}"]) + "\n", encoding="utf-8", newline="\n")


def lua_str(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def refresh(source: Path) -> None:
    for name, rel in SOURCES.items():
        src = source / rel
        if not src.exists():
            raise SystemExit(f"{src} not found: is {source} the randomizer repo?")
        shutil.copyfile(src, DATA / name)
    print(f"data/ refreshed from {source}")


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate the map tracker's Lua data tables.")
    parser.add_argument("--source", type=Path, help="randomizer repo checkout to copy data/ from first")
    args = parser.parse_args()
    if args.source:
        refresh(args.source)

    items = sorted(json.loads((DATA / "items.json").read_text(encoding="utf-8")))
    locations = json.loads((DATA / "locations.json").read_text(encoding="utf-8"))

    positions = []
    for row in (DATA / "positions.tsv").read_text(encoding="utf-8").splitlines():
        fields = row.split("\t")
        if fields[0] == "CHECK":
            positions.append((fields[1], round(float(fields[3])), round(float(fields[5]))))
    rocks = DATA / "rocks.tsv"
    if rocks.exists():
        for row in rocks.read_text(encoding="utf-8").splitlines():
            fields = row.split("\t")
            positions.append((f"{fields[0]}:{fields[1]}", round(float(fields[4])), round(float(fields[5]))))
    write("data_positions.lua", [f'    ["{key}"] = {{ {x}, {z} }},' for key, x, z in sorted(positions)])

    # Save id, kind, area, room and vanilla item of every location with a
    # save id: the tracker reads each one's state from the save by save id,
    # labels name the vanilla item in English (coin bundles as "<n> dews",
    # the currency; " x<count>" when more than one; "" without an English
    # name: the overlay then shows the kind, never an internal id). Kinds:
    # box, pickup, rock, and voyage for the Sea of Souls chests (level
    # "Voyage"; no position on the area map).
    kinds = {"BOX": "box", "PICKUP": "pickup", "ROCK": "rock"}
    english = {}
    for row in (DATA / "item_names_en.tsv").read_text(encoding="utf-8").splitlines():
        fields = row.split("\t")
        if row and not row.startswith("#") and len(fields) >= 2 and fields[1]:
            english[fields[0]] = fields[1]

    def item_text(item: str, count: int) -> str:
        if item.startswith("Coins_") and item[6:].isdigit():
            return f"{int(item[6:])} dews"   # the currency is called dew in the game
        name = english.get(item)
        if not name:
            return ""
        return f"{name} x{count}" if count > 1 else name

    icons = {}
    icons_file = DATA / "item_icons.tsv"
    if icons_file.exists():
        for row in icons_file.read_text(encoding="utf-8").splitlines():
            fields = row.split("\t")
            if row and not row.startswith("#") and len(fields) >= 2 and fields[1]:
                # The dew (currency) icon by its short name: map_overlay.lua NAMED_FRAMES.
                icons[fields[0]] = "dew" if fields[1] == COIN_FRAME else fields[1]

    save_ids = {}
    for entry in locations:
        if entry["kind"] in kinds and entry.get("save_id"):
            kind = kinds[entry["kind"]]
            if kind == "box" and entry["level"] == "Voyage":
                kind = "voyage"
            save_ids[entry["key"]] = (int(entry["save_id"]), kind, entry["level"], entry["room"],
                                      item_text(entry["item"], int(entry.get("count") or 1)), icons.get(entry["item"], ""))
    if rocks.exists():
        for row in rocks.read_text(encoding="utf-8").splitlines():
            fields = row.split("\t")
            key = f"{fields[0]}:{fields[1]}"
            if key not in save_ids and fields[3].isdigit():
                level = "Lv" + "".join(c for c in fields[0].split("_")[1].split("-")[0] if c.isdigit())
                save_ids[key] = (int(fields[3]), "rock", level, level, "Coins", "dew" if icons else "")
    write("data_locations.lua", [f'    ["{key}"] = {{ id = {sid}, kind = "{kind}", level = "{level}", room = "{room}", '
                                 f'item = {lua_str(item)}' + (f', icon = "{icon}"' if icon else "") + " },"
                                 for key, (sid, kind, level, room, item, icon) in sorted(save_ids.items())])

    # English name -> icon frame, for an item the randomizer's list names (a
    # scouted item): the Afterimage items of the item pool that have both.
    # The first item of a name wins (a few names are shared).
    by_name = {}
    for item in items:
        name = english.get(item)
        if name and icons.get(item) and name not in by_name:
            by_name[name] = icons[item]
    write("data_icons.lua", [f'    [{lua_str(name)}] = "{frame}",' for name, frame in sorted(by_name.items())])

    print(f"{len(positions)} check positions, {len(save_ids)} locations with save ids, {len(by_name)} icon names, "
          f"{sum(1 for v in save_ids.values() if v[5])} locations with an icon")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
